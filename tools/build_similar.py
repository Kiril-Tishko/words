#!/usr/bin/env python3
""""Almost the same" words: the English word and its Ukrainian twin sound almost the same and mean the same
(problem = проблема, music = музика, chocolate = шоколад), but the form differs a little, so they are not on the
identical list. Sources: data/similar.json (pairs the checkers judged "similar") and data/similar2/ok-*.json
(agents went through the 5,000 most used English words; a strict checker kept the clear ones). The similar.json pairs
in Top 20K were re-checked by the same strict checker (check-s*.txt -> ok-s*.json); the rejected ones are left out. Words already on the identical list are skipped.
Output: similar.js (window.SIMILAR, most used English words first), read by the Words page.
"""
import glob, json, os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(REPO, 'data')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_site import load_ranks, BANDS  # noqa: E402


def band_of(r):
    if not r:
        return 'rare'
    for lim, name in BANDS:
        if r <= lim:
            return name
    return 'rare'


def main():
    rank_of, rank_from_freq, freq_of = load_ranks()

    def rank(k):
        r, est = rank_of(k)
        if r and est and re.search(r'[ -]', k):   # wordfreq overrates phrases ~70x (median, calibrated on the site's phrases)
            return rank_from_freq(freq_of(k) / 70)
        return r
    ident = {w['en'].lower() for w in json.load(open(f'{D}/words.json', encoding='utf-8'))}
    # pairs a strict checker saw (check-*.txt); only the kept ones (ok-*.json) go on
    checked = set()
    for f in glob.glob(f'{D}/similar2/check-*.txt'):
        if os.path.exists(f.replace('check-', 'ok-').replace('.txt', '.json')):
            for line in open(f, encoding='utf-8'):
                if ' = ' in line:
                    checked.add(line.split(' = ', 1)[0].strip().lower())
    pairs = []
    for f in sorted(glob.glob(f'{D}/similar2/ok-*.json')):
        try:
            pairs += [(p['en'], p['uk']) for p in json.load(open(f, encoding='utf-8')) if p.get('en') and p.get('uk')]
        except Exception as e:
            print('skip', f, e)
    pairs += [(p['en'], p['uk']) for p in json.load(open(f'{D}/similar.json', encoding='utf-8'))
              if p['en'].strip().lower() not in checked]
    # English capitals from Hunspell (american -> American); Ukrainian names (Європа, Христос) are left out
    caps = {}
    hp = os.path.join(os.path.dirname(REPO), 'sources', 'en_US.dic')
    if os.path.exists(hp):
        low = set()
        for line in open(hp, encoding='utf-8', errors='ignore'):
            w = line.split('/', 1)[0].strip()
            (low.add(w) if w.islower() else caps.setdefault(w.lower(), w)) if w else None
        caps = {k: v for k, v in caps.items() if k not in low}
    out, seen = [], set()
    for en, uk in pairs:
        en, uk = en.strip(), uk.strip()
        k = en.lower()
        if k in seen or k in ident or not re.search(r'[a-zA-Z]', en) or not re.search(r'[а-яіїєґА-ЯІЇЄҐ]', uk):
            continue
        if uk[:1].isupper() and not uk.isupper():
            continue
        if en.islower() and k in caps:
            en = caps[k]
        seen.add(k)
        r = rank(k)
        out.append({'en': en, 'uk': uk, 'rank': r, 'band': band_of(r)})
    out.sort(key=lambda w: (w['rank'] is None, w['rank'] or 0, w['en'].lower()))
    with open(os.path.join(REPO, 'similar.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_similar.py — words that sound almost the same in Ukrainian.\n')
        f.write('window.SIMILAR = ' + json.dumps([{k: v for k, v in w.items() if v is not None} for w in out],
                                                ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(len(out), 'almost-the-same pairs; top:', ', '.join(f"{w['en']}={w['uk']}" for w in out[:25]))


if __name__ == '__main__':
    main()
